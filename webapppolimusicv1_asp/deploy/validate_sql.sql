SET NOCOUNT ON;
BEGIN TRANSACTION;

PRINT '--- songs.asp: list ---';
SELECT s.ID_SONG, s.SONG_NAME, s.SONG_PATH, ISNULL(s.PLAYS, 0) AS PLAYS,
       ar.NAMES AS ARTISTS, al.IMG AS ALBUM_IMAGE, al.TITLE AS ALBUM_TITLE
FROM TBL_SONG s
OUTER APPLY (SELECT STRING_AGG(a.ARTIST_NAME + ' ' + ISNULL(a.ARTIST_LASTNAME, ''), ', ')
             WITHIN GROUP (ORDER BY a.ARTIST_NAME) AS NAMES
             FROM TBL_PLAYER p INNER JOIN TBL_ARTIST a ON a.ID_ARTIST = p.ID_ARTIST
             WHERE p.ID_SONG = s.ID_SONG) ar
OUTER APPLY (SELECT TOP 1 b.ALBUM_IMAGE_PATH AS IMG, b.TITLE_ALBUM AS TITLE
             FROM TBL_TRACKLIST t INNER JOIN TBL_ALBUM b ON b.ID_ALBUM = t.ID_ALBUM
             WHERE t.ID_SONG = s.ID_SONG ORDER BY b.ID_ALBUM) al
WHERE (s.SONG_NAME LIKE '%Ad%' OR ISNULL(ar.NAMES, '') LIKE '%Ad%' OR ISNULL(al.TITLE, '') LIKE '%Ad%')
ORDER BY s.ID_SONG;

PRINT '--- default.asp: counts ---';
SELECT (SELECT COUNT(*) FROM TBL_SONG) AS SONGS,
       (SELECT COUNT(*) FROM TBL_ARTIST) AS ARTISTS,
       (SELECT COUNT(*) FROM TBL_ALBUM) AS ALBUMS,
       (SELECT ISNULL(SUM(PLAYS), 0) FROM TBL_SONG) AS PLAYS,
       (SELECT COUNT(*) FROM TBL_PLAYLIST WHERE ID_USER = 8) AS PLAYLISTS;

PRINT '--- default.asp: recent songs ---';
SELECT TOP 5 s.ID_SONG, s.SONG_NAME, s.SONG_PATH, ISNULL(s.PLAYS, 0) AS PLAYS,
       ar.NAMES AS ARTISTS, al.IMG AS ALBUM_IMAGE
FROM TBL_SONG s
OUTER APPLY (SELECT STRING_AGG(a.ARTIST_NAME + ' ' + ISNULL(a.ARTIST_LASTNAME, ''), ', ')
             WITHIN GROUP (ORDER BY a.ARTIST_NAME) AS NAMES FROM TBL_PLAYER p
             INNER JOIN TBL_ARTIST a ON a.ID_ARTIST = p.ID_ARTIST WHERE p.ID_SONG = s.ID_SONG) ar
OUTER APPLY (SELECT TOP 1 b.ALBUM_IMAGE_PATH AS IMG FROM TBL_TRACKLIST t
             INNER JOIN TBL_ALBUM b ON b.ID_ALBUM = t.ID_ALBUM WHERE t.ID_SONG = s.ID_SONG
             ORDER BY b.ID_ALBUM) al
ORDER BY s.ID_SONG DESC;

PRINT '--- default.asp: albums / artists / playlists ---';
SELECT TOP 6 b.ID_ALBUM, b.TITLE_ALBUM, b.RELEASE_YEAR, b.ALBUM_IMAGE_PATH,
       (SELECT COUNT(*) FROM TBL_TRACKLIST t WHERE t.ID_ALBUM = b.ID_ALBUM) AS TRACKS
FROM TBL_ALBUM b ORDER BY b.ID_ALBUM;

SELECT TOP 6 a.ID_ARTIST, a.ARTIST_NAME, a.ARTIST_LASTNAME, a.ARTIST_IMAGE,
       (SELECT COUNT(*) FROM TBL_PLAYER p WHERE p.ID_ARTIST = a.ID_ARTIST) AS SONGS
FROM TBL_ARTIST a ORDER BY a.ARTIST_NAME;

SELECT TOP 4 p.ID_PLAYLIST, p.TITLE, p.PHOTO, p.TYPE,
       (SELECT COUNT(*) FROM TBL_PLAYLIST_SONG ps WHERE ps.ID_PLAYLIST = p.ID_PLAYLIST) AS TRACKS
FROM TBL_PLAYLIST p WHERE p.ID_USER = 8 ORDER BY p.CREATION_DATE DESC, p.ID_PLAYLIST DESC;

PRINT '--- layout: nav counts + sidebar ---';
SELECT (SELECT COUNT(*) FROM TBL_SONG) AS SONGS,
       (SELECT COUNT(*) FROM TBL_ARTIST) AS ARTISTS,
       (SELECT COUNT(*) FROM TBL_ALBUM) AS ALBUMS,
       (SELECT COUNT(*) FROM TBL_PLAYLIST WHERE ID_USER = 8) AS MYPLAYLISTS;

SELECT TOP 7 ID_PLAYLIST, TITLE, PHOTO FROM TBL_PLAYLIST WHERE ID_USER = 8
ORDER BY CREATION_DATE DESC, ID_PLAYLIST DESC;

PRINT '--- artists.asp ---';
SELECT a.ID_ARTIST, a.ARTIST_NAME, a.ARTIST_LASTNAME, a.ARTIST_IMAGE,
       (SELECT COUNT(*) FROM TBL_PLAYER p WHERE p.ID_ARTIST = a.ID_ARTIST) AS SONGS,
       (SELECT COUNT(DISTINCT t.ID_ALBUM) FROM TBL_PLAYER p
        INNER JOIN TBL_TRACKLIST t ON t.ID_SONG = p.ID_SONG WHERE p.ID_ARTIST = a.ID_ARTIST) AS ALBUMS
FROM TBL_ARTIST a ORDER BY a.ARTIST_NAME, a.ARTIST_LASTNAME;

PRINT '--- albums.asp ---';
SELECT b.ID_ALBUM, b.TITLE_ALBUM, b.RELEASE_YEAR, b.ALBUM_IMAGE_PATH,
       (SELECT COUNT(*) FROM TBL_TRACKLIST t WHERE t.ID_ALBUM = b.ID_ALBUM) AS TRACKS
FROM TBL_ALBUM b ORDER BY b.RELEASE_YEAR DESC, b.TITLE_ALBUM;

PRINT '--- album_detail.asp ---';
SELECT ID_ALBUM, TITLE_ALBUM, RELEASE_YEAR, ALBUM_IMAGE_PATH FROM TBL_ALBUM WHERE ID_ALBUM = 1;

SELECT s.ID_SONG, s.SONG_NAME, s.SONG_PATH, ISNULL(s.PLAYS, 0) AS PLAYS, ar.NAMES AS ARTISTS
FROM TBL_TRACKLIST t INNER JOIN TBL_SONG s ON s.ID_SONG = t.ID_SONG
OUTER APPLY (SELECT STRING_AGG(a.ARTIST_NAME + ' ' + ISNULL(a.ARTIST_LASTNAME, ''), ', ')
             WITHIN GROUP (ORDER BY a.ARTIST_NAME) AS NAMES FROM TBL_PLAYER p
             INNER JOIN TBL_ARTIST a ON a.ID_ARTIST = p.ID_ARTIST WHERE p.ID_SONG = s.ID_SONG) ar
WHERE t.ID_ALBUM = 1 ORDER BY s.ID_SONG;

PRINT '--- playlists.asp ---';
SELECT p.ID_PLAYLIST, p.ID_USER, p.TITLE, p.CREATION_DATE, p.TYPE, p.PHOTO, u.USERNAME,
       CASE WHEN p.ID_USER = 8 THEN 1 ELSE 0 END AS IS_MINE,
       (SELECT COUNT(*) FROM TBL_PLAYLIST_SONG ps WHERE ps.ID_PLAYLIST = p.ID_PLAYLIST) AS TRACKS
FROM TBL_PLAYLIST p INNER JOIN TBL_USER u ON u.ID_USER = p.ID_USER
WHERE (p.ID_USER = 8 OR p.TYPE = 0 OR 0 = 1)
ORDER BY IS_MINE DESC, p.CREATION_DATE DESC, p.ID_PLAYLIST DESC;

PRINT '--- playlist_detail.asp ---';
SELECT p.ID_PLAYLIST, p.ID_USER, p.TITLE, p.CREATION_DATE, p.TYPE, p.PHOTO, u.USERNAME
FROM TBL_PLAYLIST p INNER JOIN TBL_USER u ON u.ID_USER = p.ID_USER WHERE p.ID_PLAYLIST = 1;

SELECT s.ID_SONG, s.SONG_NAME, s.SONG_PATH, ISNULL(s.PLAYS, 0) AS PLAYS, ar.NAMES AS ARTISTS, al.IMG AS ALBUM_IMAGE
FROM TBL_PLAYLIST_SONG ps INNER JOIN TBL_SONG s ON s.ID_SONG = ps.ID_SONG
OUTER APPLY (SELECT STRING_AGG(a.ARTIST_NAME + ' ' + ISNULL(a.ARTIST_LASTNAME, ''), ', ')
             WITHIN GROUP (ORDER BY a.ARTIST_NAME) AS NAMES FROM TBL_PLAYER p
             INNER JOIN TBL_ARTIST a ON a.ID_ARTIST = p.ID_ARTIST WHERE p.ID_SONG = s.ID_SONG) ar
OUTER APPLY (SELECT TOP 1 b.ALBUM_IMAGE_PATH AS IMG FROM TBL_TRACKLIST t
             INNER JOIN TBL_ALBUM b ON b.ID_ALBUM = t.ID_ALBUM WHERE t.ID_SONG = s.ID_SONG
             ORDER BY b.ID_ALBUM) al
WHERE ps.ID_PLAYLIST = 1 ORDER BY s.SONG_NAME;

SELECT ID_SONG, SONG_NAME FROM TBL_SONG WHERE ID_SONG NOT IN
(SELECT ID_SONG FROM TBL_PLAYLIST_SONG WHERE ID_PLAYLIST = 1) ORDER BY SONG_NAME;

SELECT COUNT(*) FROM TBL_PLAYLIST_SONG WHERE ID_PLAYLIST = 1 AND ID_SONG = 1;
SELECT COUNT(*) FROM TBL_SONG WHERE ID_SONG = 1;

PRINT '--- users.asp ---';
SELECT u.ID_USER, u.USERNAME, u.EMAIL, u.BIRTHDAY, u.USER_PHOTO, u.USER_TYPE,
       (SELECT COUNT(*) FROM TBL_PLAYLIST p WHERE p.ID_USER = u.ID_USER) AS PLAYLISTS
FROM TBL_USER u ORDER BY u.USER_TYPE DESC, u.USERNAME;
SELECT COUNT(*) FROM TBL_USER WHERE USER_TYPE = 1;
SELECT COUNT(*) FROM TBL_USER WHERE USER_TYPE = 0;

PRINT '--- auth ---';
SELECT TOP 1 ID_USER, USERNAME, USER_TYPE, USER_PHOTO, EMAIL
FROM TBL_USER
WHERE USERNAME = 'username1' AND (PASSWORD = '12345678' OR UPPER(PASSWORD) =
      CONVERT(VARCHAR(40), HASHBYTES('SHA1', CAST('12345678' AS VARCHAR(50))), 2));

SELECT CONVERT(VARCHAR(40), HASHBYTES('SHA1', CAST('12345678' AS VARCHAR(50))), 2) AS HASHED;
SELECT COUNT(*) FROM TBL_USER WHERE USERNAME = 'userAdmin';
SELECT COUNT(*) FROM TBL_USER WHERE EMAIL = 'usrnormal@epn.edu.ec';

PRINT '--- song_form.asp ---';
SELECT ID_SONG, SONG_NAME, SONG_PATH, ISNULL(PLAYS, 0) AS PLAYS FROM TBL_SONG WHERE ID_SONG = 1;
SELECT ISNULL(STRING_AGG(CAST(ID_ARTIST AS VARCHAR(12)), ','), '') FROM TBL_PLAYER WHERE ID_SONG = 1;
SELECT TOP 1 ID_ALBUM FROM TBL_TRACKLIST WHERE ID_SONG = 1;

INSERT INTO TBL_SONG (SONG_NAME, SONG_PATH, PLAYS) OUTPUT INSERTED.ID_SONG
VALUES ('__test song', '~/songFiles/test.mp3', 0);

DECLARE @newSong INT = SCOPE_IDENTITY();
