DELETE FROM TBL_ARTIST WHERE ID_ARTIST = (SELECT MAX(ID_ARTIST) FROM TBL_ARTIST);

INSERT INTO TBL_ALBUM (TITLE_ALBUM, RELEASE_YEAR, ALBUM_IMAGE_PATH) OUTPUT INSERTED.ID_ALBUM
VALUES ('__test album', 1999, '~/albumImages/album1.png');
