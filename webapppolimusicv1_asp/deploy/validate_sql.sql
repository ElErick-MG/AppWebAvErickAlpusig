       (SELECT COUNT(*) FROM TBL_ARTIST) AS ARTISTS, (SELECT COUNT(*) FROM TBL_ALBUM) AS ALBUMS,
       (SELECT COUNT(*) FROM TBL_PLAYLIST) AS PLAYLISTS;

