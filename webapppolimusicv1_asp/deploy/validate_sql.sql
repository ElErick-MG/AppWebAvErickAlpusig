VALUES (8, '__test playlist', '2026-10-18T19:30:00', 0, '~/playlistImages/default.jpg');
UPDATE TBL_PLAYLIST SET TITLE = '__test playlist 2', TYPE = 1, PHOTO = '~/playlistImages/default.jpg'
WHERE ID_PLAYLIST = (SELECT MAX(ID_PLAYLIST) FROM TBL_PLAYLIST);
