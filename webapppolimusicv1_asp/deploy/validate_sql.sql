SELECT ISNULL(PLAYS, 0) FROM TBL_SONG WHERE ID_SONG = 1;

PRINT '--- artist / album forms ---';
INSERT INTO TBL_ARTIST (ARTIST_NAME, ARTIST_LASTNAME, ARTIST_IMAGE) OUTPUT INSERTED.ID_ARTIST
VALUES ('__test', 'artist', '~/ArtistImages/artist1.jpg');
